#: Inclusive datetime range for ``{current_datetime}`` substitution.

_DATETIME_RANGE_START = datetime.datetime(2026, 3, 1, 0, 0, 0)
_DATETIME_RANGE_END = datetime.datetime(2026, 4, 30, 23, 59, 59)


def sample_current_datetime(seed: int, index: int) -> str:
    'Deterministically sample a datetime in March–April 2026.\n\n\n    The same ``(seed, index)`` always yields the same datetime string, so the\n    unified dataset is reproducible by ``--seed``.'
    rng = random.Random(seed + index)
    span = (_DATETIME_RANGE_END - _DATETIME_RANGE_START).total_seconds()
    offset = rng.uniform(0.0, span)
    dt = _DATETIME_RANGE_START + datetime.timedelta(seconds=offset)
    return dt.strftime("%Y-%m-%d %H:%M:%S")


def format_system_prompt(current_datetime: str) -> str:
    'Fill the ``{current_datetime}`` placeholder in the system prompt.\n\n\n    Uses ``str.replace`` (not ``str.format``) so the rest of the prompt — which\n    contains backticks and markdown but no other braces — is left untouched.'
    filled = QA_SYSTEM_PROMPT.replace("{current_datetime}", current_datetime)
    assert "{current_datetime}" not in filled, "placeholder not substituted"
    return filled
